type StaticInterviewCategory = InterviewQuestion["category"] | "VERIFICATION";
type StaticInterviewQuestion = Omit<InterviewQuestion, "category"> & {
  category: StaticInterviewCategory;
};

type InterviewQuestionSeed = readonly [
  id: string,
  category: StaticInterviewCategory,
  difficulty: InterviewQuestion["difficulty"],
  question: string,
  answer: string,
  relatedSkillIds: string[],
  relatedProjectIds: string[],
  tags: string[],
];

function createQuestion([
  id,
  category,
  difficulty,
  question,
  answer,
  relatedSkillIds,
  relatedProjectIds,
  tags,
]: InterviewQuestionSeed): StaticInterviewQuestion {
  return {
    id,
    category,
    difficulty,
    question,
    answer,
    relatedSkillIds,
    relatedProjectIds,
    tags,
  };
}

